"""generate_vjepa2_project.py — the V-JEPA 2 video classifier
(facebook/vjepa2-vitl-fpc16-256-ssv2) + its calibrated formats -> the KV260
project behind libvjepa2.so (doc/plans/VJEPA2_PLAN.md).

  1. src/vjepa2.py: the entry ``clip`` (the patch rows of a 16-frame clip ->
     the logits), every exponent from the formats of vjepa2_study.py formats
  2. inference-scheduler: OnnxGraph + MultiEntryGenerator -> <out>/ (CMake
     project, weights/*.dat)
  3. driver/ for the kernels the entry drives, test/vjepa2_api.{c,h} +
     test/vjepa2_bench.c + test/vjepa2_glue.h (inference_init with the
     project's kernels, the entry's run function, the model's constants and
     class names), CMake targets vjepa2_bench and vjepa2 (the shared library:
     only the vjepa2_* symbols exported), project.json, layers.json

usage: inference-scheduler/.venv/bin/python demo/video_classification/scripts/generate_vjepa2_project.py
           [--assets demo/video_classification/assets] [--formats JSON]
           [--out-dir demo/video_classification/build/vjepa2_project] [--driver-dirs JSON]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.join(REPO, "inference-scheduler"))

from src.checkpoint import load_safetensors             # noqa: E402
from src.codegen.multi import MultiEntryGenerator       # noqa: E402
from src.graph import OnnxGraph                         # noqa: E402
from src.vjepa2 import VJepa2Config, VJepa2Formats, VJepa2Frontend   # noqa: E402

DEMO = os.path.join(REPO, "demo", "video_classification")
ASSETS = os.path.join(DEMO, "assets")
CKPT = "vjepa2-vitl-fpc16-256-ssv2"
SRC = os.path.join(DEMO, "src")
C_SOURCES = ("vjepa2_api.c", "vjepa2_api.h", "vjepa2_bench.c")    # + the generated test/vjepa2_glue.h
POLICY = "pow2+p12+vgelu+vsmx+rowops"                             # the formats' policy (vjepa2_q.POLICIES)


def driver_dirs_from_config(path: str) -> dict:
    """local.driver_dirs of demo/bert_squad/bert_squad_config.json."""
    if not os.path.exists(path):
        return {}
    cfg = json.load(open(path))
    base = os.path.dirname(os.path.abspath(path))
    out = {}
    for k, v in (cfg.get("local", {}).get("driver_dirs") or {}).items():
        if k.startswith("_") or not v:
            continue
        v = os.path.expanduser(v)
        out[k] = v if os.path.isabs(v) else os.path.normpath(os.path.join(base, v))
    return out


def populate_drivers(out: str, driver_dirs: dict, active) -> list:
    """driver/: the active kernels' driver files; returns the missing ones."""
    dst = os.path.join(out, "driver")
    os.makedirs(dst, exist_ok=True)
    missing = []
    for kd in active:
        src = driver_dirs.get(kd.name)
        for f in kd.driver_files:
            p = os.path.join(src, f) if src else None
            if p and os.path.exists(p):
                shutil.copy2(p, os.path.join(dst, f))
            else:
                missing.append(f"{kd.name}/{f}")
    return missing


def default_formats() -> str:
    return os.path.join(DEMO, f"vjepa2_vitl_ssv2_{POLICY}_formats.json")


def load(assets: str, formats: str):
    """(VJepa2Config, the checkpoint's tensors, VJepa2Formats)."""
    cfg = VJepa2Config.from_dir(os.path.join(assets, CKPT))
    W = load_safetensors(os.path.join(assets, CKPT, "model.safetensors"))
    return cfg, W, VJepa2Formats.from_file(formats, cfg)


def _c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_glue(out: str, cfg: VJepa2Config, fe: VJepa2Frontend, active) -> None:
    """test/vjepa2_glue.h: inference_init() with the project's kernels, the entry's
    run function, the model's constants and class names."""
    rows = ", ".join(f"{r}u" for r, _k in fe.pieces)
    ins = ", ".join(f"rows[{i}]" for i in range(len(fe.pieces)))
    labels = ",\n".join("    " + _c_string(s) for s in cfg.labels)
    text = (
        "/* vjepa2_glue.h - generated by demo/video_classification/scripts/generate_vjepa2_project.py:\n"
        " * the entry clip of src/vjepa2.py. */\n"
        "#ifndef VJEPA2_GLUE_H\n#define VJEPA2_GLUE_H\n\n"
        f"#define VJ_FRAMES   {cfg.frames}      /* frames per clip */\n"
        f"#define VJ_TUBELET  {cfg.tub}\n"
        f"#define VJ_PATCH    {cfg.P}\n"
        f"#define VJ_CROP     {cfg.S}      /* the model's square frame */\n"
        f"#define VJ_SHORT    {cfg.short}      /* the resize's shorter side */\n"
        f"#define VJ_TOKENS   {cfg.N}\n"
        f"#define VJ_CLASSES  {cfg.C}\n"
        f"#define VJ_PIECES   {len(fe.pieces)}      /* the entry's inputs: the patch rows in pieces */\n"
        f"static const unsigned vj_piece_rows[VJ_PIECES] = {{ {rows} }};\n\n"
        f"static const char *const vj_labels[VJ_CLASSES] = {{\n{labels}\n}};\n\n"
        "/* inference_init() with every kernel the project drives (" + ", ".join(kd.name for kd in active)
        + ") */\nstatic int vj_glue_init(void)\n{\n"
        f"    return inference_init({', '.join(kd.instance_macro for kd in active)});\n}}\n\n"
        "static void vj_glue_clip(inference_buf_t *const *rows, float *logits)\n{\n"
        f"    inference_run_clip({ins}, logits);\n}}\n\n#endif\n")
    with open(os.path.join(out, "test", "vjepa2_glue.h"), "w") as f:
        f.write(text)


def patch_cmake(out: str, cg, lib: str) -> None:
    path = os.path.join(out, "CMakeLists.txt")
    text = open(path).read()
    macros = "\n".join(f"            {kd.instance_macro}" for kd in cg._active_kernels)
    text += (
        "\n"
        "# -----------------------------------------------------------------------\n"
        f"# vjepa2_bench — the board gate runner, and {lib} — lib{lib}.so, both over\n"
        "# test/vjepa2_api.c (added by demo/video_classification/scripts/\n"
        "# generate_vjepa2_project.py).  Only the vjepa2_* symbols of the shared\n"
        "# library are exported.\n"
        "# -----------------------------------------------------------------------\n"
        "if(INFERENCE_TARGET STREQUAL \"LINUX\")\n"
        "    set_property(TARGET inference PROPERTY POSITION_INDEPENDENT_CODE ON)\n"
        "    add_executable(vjepa2_bench test/vjepa2_bench.c test/vjepa2_api.c)\n"
        "    target_link_libraries(vjepa2_bench PRIVATE inference m pthread)\n"
        f"    add_library({lib} SHARED test/vjepa2_api.c)\n"
        f"    target_link_libraries({lib} PRIVATE inference m pthread)\n"
        f"    target_link_options({lib} PRIVATE -Wl,--exclude-libs,ALL -Wl,--no-undefined)\n"
        f"    foreach(_tgt IN ITEMS vjepa2_bench {lib})\n"
        "        target_include_directories(${_tgt} PRIVATE test)\n"
        "        target_compile_options(${_tgt} PRIVATE -Wall -Wextra -O2)\n"
        "        target_compile_definitions(${_tgt} PRIVATE\n"
        "            VJEPA2_API_WEIGHTS_DIR=\"${INFERENCE_WEIGHTS_DIR}\")\n"
        "        foreach(_macro IN ITEMS\n"
        f"{macros})\n"
        "            if(DEFINED ${_macro})\n"
        "                target_compile_definitions(${_tgt} PRIVATE ${_macro}=${${_macro}})\n"
        "            endif()\n"
        "        endforeach()\n"
        "    endforeach()\n"
        "endif()\n")
    with open(path, "w") as f:
        f.write(text)


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def generate(out: str, cfg: VJepa2Config, W: dict, fmt: VJepa2Formats, lib: str = "vjepa2",
             driver_dirs: dict = None, extra: dict = None, **fe_kw) -> dict:
    """Write the project into ``out`` (replaced); returns project.json's contents.
    ``fe_kw``: VJepa2Frontend's pieces / parts (tests)."""
    t0 = time.time()
    fe = VJepa2Frontend(cfg, W, fmt, name=lib, **fe_kw)
    entries = [("clip", OnnxGraph(fe.entry()))]
    cg = MultiEntryGenerator(entries, lib)
    out = os.path.abspath(out)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    summary = cg.write_project(out)
    missing = populate_drivers(out, driver_dirs or {}, cg._active_kernels)
    for name in C_SOURCES:
        shutil.copy2(os.path.join(SRC, name), os.path.join(out, "test", name))
    write_glue(out, cfg, fe, cg._active_kernels)
    patch_cmake(out, cg, lib)
    layers = [{"i": sn.index, "entry": "clip", "name": sn.onnx_node.name, "op": sn.onnx_node.op_type,
               "kind": "conv" if sn.kernel_name == "ConvKernel" else sn.onnx_node.op_type}
              for sn in entries[0][1].nodes]
    json.dump(layers, open(os.path.join(out, "layers.json"), "w"), indent=0)
    summary.update({"model": CKPT, "library": f"lib{lib}.so", "frames": cfg.frames, "crop": cfg.S,
                    "short_side": cfg.short, "tokens": cfg.N, "classes": cfg.C,
                    "pieces": [list(p) for p in fe.pieces], "parts": fe.parts,
                    "nodes": {n: len(eg.nodes) for n, eg in entries},
                    "missing_drivers": missing, "generated_s": round(time.time() - t0, 1)})
    summary.update(extra or {})
    json.dump(summary, open(os.path.join(out, "project.json"), "w"), indent=2)
    return summary


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().split("\n\n")[0])
    ap.add_argument("--assets", default=ASSETS, help=f"{CKPT}/ (vjepa2_study.py fetch)")
    ap.add_argument("--formats", default=None, help="the calibrated exponents (default demo/video_classification/"
                                                    f"vjepa2_vitl_ssv2_{POLICY}_formats.json)")
    ap.add_argument("--out-dir", default=os.path.join(DEMO, "build", "vjepa2_project"))
    ap.add_argument("--driver-dirs", default=None,
                    help="JSON {kernel: dir}; default: local.driver_dirs of demo/bert_squad/bert_squad_config.json")
    a = ap.parse_args(argv)
    formats = a.formats or default_formats()
    cfg, W, fmt = load(a.assets, formats)
    dd = json.loads(a.driver_dirs) if a.driver_dirs else driver_dirs_from_config(
        os.path.join(REPO, "demo", "bert_squad", "bert_squad_config.json"))
    summary = generate(a.out_dir, cfg, W, fmt, driver_dirs=dd,
                       extra={"assets": os.path.abspath(a.assets), "formats": os.path.abspath(formats),
                              "formats_sha256": _sha256(formats)})
    print(f"project: {os.path.abspath(a.out_dir)} ({sum(summary['nodes'].values())} nodes, pool "
          f"{summary['pool_bytes'] / 2**20:.1f} MiB, {summary['generated_s']} s)"
          + (f"; missing drivers: {summary['missing_drivers']}" if summary["missing_drivers"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
