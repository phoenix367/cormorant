def files():
    f = {f"src/{FILE}_hw.h": hw_h(), f"src/{FILE}.h": driver_h(), f"src/{FILE}.c": driver_c(),
         f"src/{FILE}_linux.c": linux_c(), f"src/{FILE}_sinit.c": sinit_c()}
    f.update(data_files())
    return f


def write(out_dir):
    root = os.path.join(out_dir, f"{NAME}_v1_0")
    for rel, text in files().items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # keep the timestamp of an unchanged file (make does not rebuild its users)
        if os.path.exists(path) and open(path).read() == text:
            continue
        with open(path, "w") as fh:
            fh.write(text)
    return root


