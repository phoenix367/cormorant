def rtl_localparams(path=RTL_CTRL):
    """{localparam name: value} of the N'hXX address constants in the RTL control block."""
    text = re.sub(r"//[^\n]*", "", open(path).read())
    return {n: int(v, 16) for n, v in re.findall(r"\b(A_\w+)\s*=\s*\d+'h([0-9A-Fa-f]+)", text)}


def check_rtl(path=RTL_CTRL):
    errors = []
    lp = rtl_localparams(path)
    want = {}
    for name, off, rtl in CTRL:
        want[rtl] = (name, off)
    for name, off, bits, rtl in REGS:
        for i, p in enumerate(rtl):
            want[p] = (name + (f" word {i}" if bits == 64 else ""), off + 4 * i)
        if len(rtl) != bits // 32:
            errors.append(f"{name}: {bits} bits but {len(rtl)} RTL address constants")
    for p, (what, off) in want.items():
        if p not in lp:
            errors.append(f"{what}: {p} is not defined in {os.path.relpath(path, KERNEL_DIR)}")
        elif lp[p] != off:
            errors.append(f"{what}: {p} = 0x{lp[p]:02X} in the RTL, 0x{off:02X} in the driver table")
    for p in sorted(set(lp) - set(want)):
        errors.append(f"RTL address constant {p} = 0x{lp[p]:02X} is not in the driver table")
    return errors


def _defines(text):
    return {n: v for n, v in re.findall(r"#define\s+(\w+_CTRL_(?:ADDR|BITS)_\w+)\s+(\w+)", text)}


def _prototypes(text):
    text = re.sub(r"\s+", " ", text)
    return set(re.findall(rf"\b(?:void|u32|u64|int|{PREFIX}_Config\*) {PREFIX}_\w+\([^)]*\);", text))


def check_hls(hls_dir):
    """The HLS export's register offsets and prototypes against the generated driver."""
    src = os.path.join(hls_dir, "src")
    gen = files()
    errors = []
    hls_def = _defines(open(os.path.join(src, f"{FILE}_hw.h")).read())
    our_def = _defines(gen[f"src/{FILE}_hw.h"])
    for n in sorted(set(hls_def) | set(our_def)):
        a, b = hls_def.get(n), our_def.get(n)
        if a is None or b is None or int(a, 0) != int(b, 0):
            errors.append(f"{n}: HLS {a}, generated {b}")
    hls_p = _prototypes(open(os.path.join(src, f"{FILE}.h")).read())
    our_p = _prototypes(gen[f"src/{FILE}.h"])
    for p in sorted(hls_p - our_p):
        errors.append(f"only in the HLS driver: {p}")
    for p in sorted(our_p - hls_p):
        errors.append(f"only in the generated driver: {p}")
    return errors


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    ap.add_argument("--out", help=f"write DIR/{NAME}_v1_0/{{src,data}}/")
    ap.add_argument("--check", action="store_true",
                    help=f"compare the register table with rtl/{os.path.basename(RTL_CTRL)}")
    ap.add_argument("--rtl", metavar="SV", default=RTL_CTRL,
                    help=f"with --check: the RTL control block (default: rtl/{os.path.basename(RTL_CTRL)})")
    ap.add_argument("--hls-driver", metavar="DIR",
                    help=f"with --check: also compare with the HLS export's {NAME}_v1_0 driver")
    ap.add_argument("--json", action="store_true",
                    help="with --check: print {registers, errors} as JSON and exit 0 (the caller judges)")
    a = ap.parse_args(argv)
    if not a.out and not a.check:
        ap.error("nothing to do: give --out and / or --check")
    if a.out:
        root = write(a.out)
        if not a.json:
            print(f"driver -> {root}")
    if a.check:
        errors = check_rtl(a.rtl)
        if a.hls_driver:
            errors += check_hls(a.hls_driver)
        if a.json:
            regs = {n: {"offset": off, "bits": bits} for n, off, bits, _ in REGS}
            print(json.dumps({"registers": regs, "errors": errors}))
            return 0
        else:
            for e in errors:
                print("MISMATCH", e)
            what = "RTL" + (" and HLS driver" if a.hls_driver else "")
            print(f"register table vs {what}: " + (f"{len(errors)} mismatches" if errors else
                                                 f"{len(REGS)} arguments + {len(CTRL)} control registers agree"))
        return 1 if errors else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
